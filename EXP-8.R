
# Q8. Scatter Plot for Mobile Phones Sold and Money

# Input Data
x <- c(4, 1, 5, 7, 10, 2, 50, 25, 90, 36)
y <- c(12, 5, 13, 19, 31, 7, 153, 72, 275, 110)

# Draw Scatter Plot
scatter.smooth(x, y,
               main = "Scatter Plot",
               xlab = "Number of Mobile Phones Sold",
               ylab = "Money")
